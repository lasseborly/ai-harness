const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const { Store } = require('../core/store.cjs');
const { WorkspaceHistory, titleFrom } = require('../core/workspace-history.cjs');
async function setup(t) {
  const root = await fs.mkdtemp(path.join(os.tmpdir(),'harness-history-'));
  t.after(() => fs.rm(root,{recursive:true,force:true}));
  const history = new WorkspaceHistory(new Store(path.join(root,'state')));
  return {root,history};
}
const run = (messages, extra = {}) => ({ messages, plan: null, planConversation: [], status: 'idle', mode: 'plan', ...extra });
test('kladde, plan og samtale genåbnes fra appdata uden tilladelser eller projektændringer', async t => {
  const {root,history}=await setup(t); const project={root:path.join(root,'projekt med mellemrum'),name:'Testprojekt'};
  await fs.mkdir(project.root); const {active:id}=await history.open(project);
  const plan={id:'p1',text:'En plan',context:'Afklaringen'};
  await history.saveRun(project.root,id,run([{id:'u',role:'user',text:'Min idé',apiKey:'må ikke gemmes'},{id:'a',role:'assistant',text:'Mit forslag'}],{plan,planConversation:['Min idé','Mit forslag']}));
  await Promise.all([history.draft(project.root,id,{text:'Ny kladde',mode:'plan'}),history.saveRun(project.root,id,run([],{plan,planConversation:['Min idé','Mit forslag']}))]);
  const fresh=new WorkspaceHistory(history.store); const reopened=await fresh.open(project);
  assert.equal(reopened.active,id); assert.equal(reopened.version,2);
  const chat=await fresh.openChat(project.root,id);
  assert.equal(chat.draft,'Ny kladde'); assert.equal(chat.plan.id,'p1'); assert.equal(chat.messages.length,2); assert.equal(chat.title,'Min idé');
  for (const file of [history.file(project.root),history.chatFile(project.root,id)]) assert.equal((await fs.readFile(file,'utf8')).includes('må ikke gemmes'),false);
  assert.deepEqual(await fs.readdir(project.root),[]); assert.equal((await fresh.recent())[0].root,project.root);
});
test('afbrudt opgave bliver ikke genstartet eller præsenteret som en godkendt plan', async t => {
  const {root,history}=await setup(t); const project={root,name:'Afbrudt'};
  const {active:id}=await history.open(project);
  await history.saveRun(root,id,run([{id:'u',role:'user',text:'Fortsæt min idé'}],{plan:{id:'gammel'},status:'working',mode:'build',clearDraft:true}));
  const reopened=await history.openChat(root,id);
  assert.equal(reopened.status,'interrupted'); assert.equal(reopened.plan,null); assert.equal(reopened.lastPlan.reason,'afbrudt'); assert.equal(reopened.draft,'Fortsæt min idé');
  assert.equal((await history.chats(root))[0].status,'interrupted','sidepanelet ser også, at opgaven blev afbrudt');
});
test('projekter og samtaler holdes adskilt, og en beskadiget samtalefil bevares', async t => {
  const {history}=await setup(t);
  const a=(await history.open({root:'/projekt-a',name:'A'})).active, b=(await history.open({root:'/projekt-b',name:'B'})).active;
  await history.draft('/projekt-a',a,{text:'A',mode:'plan'}); await history.draft('/projekt-b',b,{text:'B',mode:'free'});
  assert.equal((await history.readChat('/projekt-a',a)).draft,'A'); assert.equal((await history.readChat('/projekt-b',b)).mode,'free');
  await assert.rejects(history.readChat('/projekt-a',b),/findes ikke/);
  assert.throws(() => history.draft('/projekt-a',a,{text:'A',mode:'ukendt'}),/Ugyldig/);
  assert.throws(() => history.chatFile('/projekt-a','../projekt-b'),/findes ikke/,'en samtale-id kan ikke pege uden for mappen');
  const file=history.chatFile('/projekt-a',a); await fs.writeFile(file,'beskadiget');
  await assert.rejects(history.draft('/projekt-a',a,{text:'overskriv',mode:'plan'}),/bevaret/);
  assert.equal(await fs.readFile(file,'utf8'),'beskadiget');
});
