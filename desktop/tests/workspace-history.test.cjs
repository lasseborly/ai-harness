test('ny samtale efter en beskadiget projektfil gemmer filen til side og finder samtalerne igen', async t => {
  const {root,history}=await setup(t);
  const {active:id}=await history.open({root,name:'Arkiv'});
  await history.saveRun(root,id,run([{id:'u',role:'user',text:'Den første samtale'}]));
  await fs.writeFile(history.file(root), 'beskadiget indhold, der skal bevares');
  await assert.rejects(history.open({root,name:'Arkiv'}),/kan ikke læses.*\+/);
  assert.equal(await fs.readFile(history.file(root),'utf8'),'beskadiget indhold, der skal bevares','åbning alene ændrer intet');
  const chat=await history.createChat(root);
  assert.notEqual(chat.id,id); assert.equal(chat.draft,'');
  const archive=history.file(root).replace(/\.json$/, '')+'-archives';
  const entries=await fs.readdir(archive);
  assert.equal(entries.length,1);
  assert.equal(await fs.readFile(path.join(archive,entries[0]),'utf8'),'beskadiget indhold, der skal bevares');
  const project=await history.project(root);
  assert.deepEqual(project.chats.map(item=>item.id).sort(),[id,chat.id].sort()); assert.equal(project.active,chat.id);
  assert.equal((await history.chats(root)).find(item=>item.id===id).title,'Den første samtale');
});
test('en ældre samtale og arkiverede samtaler flyttes til samtalefiler, og arkivet bevares', async t => {
  const {root,history}=await setup(t);
  const file=history.file(root), archive=file.replace(/\.json$/, '')+'-archives';
  await fs.mkdir(archive,{recursive:true});
  const old=(text,at,extra={})=>({version:1,draft:'',mode:'plan',messages:text?[{id:'u-'+at,role:'user',text},{id:'a-'+at,role:'assistant',text:'Svar'}]:[],plan:null,planConversation:[],status:'idle',updatedAt:at,...extra});
  await fs.writeFile(path.join(archive,'1.json'),JSON.stringify(old('Byg en bookingside. Med kalender','2026-09-01T10:00:00.000Z')));
  await fs.writeFile(path.join(archive,'2.json'),JSON.stringify(old('Lav en quiz','2026-09-02T10:00:00.000Z',{status:'working'})));
  await fs.writeFile(path.join(archive,'3.json'),JSON.stringify(old('','2026-09-03T10:00:00.000Z')));
  await fs.writeFile(path.join(archive,'4.json'),'beskadiget arkiv');
  const brief={version:1,idea:'Booking'};
  await fs.mkdir(path.dirname(file),{recursive:true});
  await fs.writeFile(file,JSON.stringify({...old('Den aktuelle samtale','2026-09-04T10:00:00.000Z',{draft:'Min kladde',plan:{id:'p',text:'Plan'}}),brief,restorationID:'gendannelse-1'}));
  const before=await fs.readdir(archive);
  const project=await history.open({root,name:'Gammel'});
  assert.equal(project.version,2); assert.deepEqual(project.brief,brief); assert.equal(project.restorationID,'gendannelse-1'); assert.ok(project.migratedAt);
  assert.equal(project.chats.length,3,'tomme og beskadigede arkivfiler springes over');
  const current=await history.readChat(root,project.active);
  assert.equal(current.draft,'Min kladde'); assert.equal(current.plan.id,'p'); assert.equal(current.title,'Den aktuelle samtale');
  const list=await history.chats(root);
  assert.deepEqual(list.map(item=>item.title),['Den aktuelle samtale','Lav en quiz','Byg en bookingside'],'nyeste først');
  assert.equal(list[1].status,'interrupted','en arkiveret opgave i gang står som afbrudt');
  assert.deepEqual(await fs.readdir(archive),before,'arkivet er uændret');
  assert.equal((await history.open({root,name:'Gammel'})).active,project.active,'flytningen sker kun én gang');
});
test('en ny samtale genbruger en tom samtale, og tomme samtaler vises ikke', async t => {
  t.mock.timers.enable({ apis: ['Date'], now: new Date('2026-10-15T10:00:00Z') });
  const {root,history}=await setup(t);
  const {active:first}=await history.open({root,name:'Samtaler'});
  assert.equal((await history.createChat(root)).id,first,'den tomme samtale genbruges');
  await history.saveRun(root,first,run([{id:'u',role:'user',text:'Første'}]));
  t.mock.timers.tick(1000);
  const second=(await history.createChat(root)).id; assert.notEqual(second,first);
  await history.draft(root,second,{text:'Kun en kladde',mode:'plan'});
  t.mock.timers.tick(1000);
  const third=(await history.createChat(root)).id; assert.notEqual(third,second,'en samtale med kladde genbruges ikke');
  assert.deepEqual((await history.chats(root)).map(item=>item.id),[third,second,first]);
  assert.equal((await history.chats(root)).find(item=>item.id===second).title,'Kun en kladde','en samtale uden beskeder hedder det, man er begyndt at skrive');
  await history.openChat(root,first);
  assert.deepEqual((await history.chats(root)).map(item=>item.id).sort(),[first,second].sort(),'en tom samtale, der ikke er åben, vises ikke');
});
test('omdøbning holder, og sletning flytter samtalefilen og vælger den nyeste', async t => {
  const {root,history}=await setup(t);
  const {active:a}=await history.open({root,name:'Navne'});
  await history.saveRun(root,a,run([{id:'u',role:'user',text:'Byg en side til klubben'}]));
  await history.renameChat(root,a,'  Klubbens side  ');
  await history.saveRun(root,a,run([{id:'u2',role:'user',text:'Noget andet'}]));
  assert.equal((await history.readChat(root,a)).title,'Klubbens side','eget navn bevares');
  await history.renameChat(root,a,'');
  assert.equal((await history.readChat(root,a)).title,'Byg en side til klubben','tomt navn giver det automatiske igen');
  assert.throws(()=>history.renameChat(root,a,'to\nlinjer'),/én linje/); assert.throws(()=>history.renameChat(root,a,'x'.repeat(81)),/80 tegn/);
  const b=(await history.createChat(root)).id; await history.saveRun(root,b,run([{id:'v',role:'user',text:'Anden'}]));
  const removed=[];
  const project=await history.removeChat(root,b,async file=>{removed.push(file);await fs.rm(file);});
  assert.deepEqual(removed,[history.chatFile(root,b)]); assert.equal(project.active,a); assert.deepEqual(project.chats.map(item=>item.id),[a]);
  await assert.rejects(history.removeChat(root,b),/findes ikke/);
  await assert.rejects(history.readChat(root,b),/findes ikke/);
});
test('alle åbnede projekter står på listen, nyeste først, også ud over de 12, sidepanelet viser først', async t => {
  const {history}=await setup(t);
  for (let i=1;i<=14;i++) await history.store.saveProject(`/projekt-${i}`,{recent:{root:`/projekt-${i}`,name:`Projekt ${i}`,at:new Date(Date.UTC(2026,9,1,i)).toISOString()}});
  await history.store.saveProject('/kun-indstillinger',{deploy:{}});
  const recent=await history.recent();
  assert.equal(recent.length,14,'et projekt uden recent er aldrig åbnet og står ikke på listen');
  assert.deepEqual(recent.slice(0,2).map(p=>p.name),['Projekt 14','Projekt 13']); assert.equal(recent.at(-1).root,'/projekt-1');
  await history.open({root:'/projekt-1',name:'Projekt 1'});
  assert.equal((await history.recent())[0].root,'/projekt-1','det ældste projekt kan åbnes igen og står derefter først');
});
test('samtalens navn er første sætning af første besked, højst 60 tegn ved et ordskifte', () => {
  assert.equal(titleFrom([{role:'assistant',text:'Hej'},{role:'user',text:'Byg en side. Den skal være blå.'}]),'Byg en side');
  assert.equal(titleFrom([{role:'user',text:'Hvad koster det?\n\nMere tekst'}]),'Hvad koster det');
  assert.equal(titleFrom([{role:'user',text:'Version 2.0 af siden'}]),'Version 2.0 af siden','punktum inde i et ord afslutter ikke');
  const long=titleFrom([{role:'user',text:'En lang beskrivelse af en side til foreningens medlemmer med kalender og tilmelding til arrangementer'}]);
  assert.ok(long.endsWith(' …')); assert.ok(long.length<=62); assert.doesNotMatch(long,/\S+[^\s…]…$/);
  assert.equal(titleFrom([]),''); assert.equal(titleFrom([{role:'user',text:'   '}]),'');
});
