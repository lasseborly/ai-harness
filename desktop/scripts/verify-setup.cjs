const { _electron: electron } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const http = require('node:http');
(async () => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'harness-setup-'));
  const project = path.join(root, 'projekt'); await fs.mkdir(project);
  let requests = 0, available = true, empty = false;
  const server = http.createServer((req, res) => {
    ++requests; res.setHeader('content-type', 'application/json');
    if (!available) { res.writeHead(503); return res.end(JSON.stringify({ error: 'Testserver utilgængelig' })); }
    res.end(JSON.stringify({ data: empty ? [] : [{ id: 'test-model', name: 'Testmodel' }] }));
  });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  let app;
  const errors = [];
  async function launch(extra = {}) {
    app = await electron.launch({ executablePath: require('electron'), args: [path.join(__dirname, '..'), '--user-data-dir=' + path.join(root, 'appdata')], env: { ...process.env, ELECTRON_RUN_AS_NODE: undefined, ...extra } });
    const page = await app.firstWindow(); await require('./ui-test-helpers.cjs').skipIntroduction(page); page.on('pageerror', error => errors.push(error.message));
    await require('./ui-test-helpers.cjs').toOnboarding(page); await page.waitForSelector('#onboarding'); await page.waitForFunction(() => !document.querySelector('#new').disabled);
    assert.equal(await page.isVisible('#setup'), false);
    assert.equal(await page.locator('#design-options').evaluate(el => el.open), false);
    assert.equal(await page.locator('#project-options').evaluate(el => el.open), false);
    await require('./ui-test-helpers.cjs').openSetup(page);
    await page.click('#setup-advanced');
    await page.waitForFunction(() => !document.querySelector('#setup-git-refresh').disabled);
    await page.click('#setup-back');
    return page;
  }
  try {
    let page = await launch();
    assert.equal(await page.isDisabled('#new'), false);
    assert.equal(await page.isDisabled('#setup-continue'), true);
    assert.equal(requests, 0);
    await page.screenshot({ path: path.join(root, 'opstart.png'), fullPage: true });
    await page.click('#setup-local'); await page.waitForSelector('#create-form');
    await page.fill('#name', 'Min kladde'); await page.fill('#purpose', 'Bevar denne idé.');
    await require('./ui-test-helpers.cjs').openSetup(page); await page.click('#setup-local');
    assert.equal(await page.inputValue('#name'), 'Min kladde');
    await require('./ui-test-helpers.cjs').openSetup(page); await page.click('#setup-add-provider');
    assert.equal(await page.isVisible('#setup-choice'),false);
    assert.equal(await page.locator('#connection-advanced').evaluate(el=>el.open),false);
    assert.equal(await page.locator('.key-guide').evaluate(el=>el.open),false);
    await page.screenshot({path:path.join(root,'forbind-din-ai.png'),animations:'disabled'});
    assert.equal(await page.locator('#provider-cards button').count(), 10, 'De ti AI-udbydere vises på lige vilkår.');
    assert.equal(await page.locator('#provider-cards [data-kind=komplai], #provider-kind option[value=komplai]').count(), 0, 'komplai Run hører kun til i Del.');
    assert.equal(await page.isVisible('#provider-kind'), false, 'formularen vises først efter valg');
    assert.equal(await page.isVisible('#api-key'), false, 'nøglefeltet vises først efter valg af udbyder');
    for (const [kind, address] of [['corti', 'https://ai.eu.corti.app/v1'], ['mistral', 'https://api.mistral.ai/v1']]) {
      await page.click(`#provider-cards [data-kind="${kind}"]`);
      assert.equal(await page.isVisible('#api-key'), true);
      assert.equal(await page.inputValue('#base-url'), address);
      assert.equal(await page.locator('#base-url').evaluate(el => el.readOnly), true);
      assert.equal(await page.isDisabled('#save-connection'), false);
      assert.equal(await page.isDisabled('#api-key'), false);
      await page.click('#setup-back');
    }
    assert.equal(await page.locator('#provider-kind option[value=promte]').count(), 0);
    await page.click('#provider-cards [data-kind="compatible"]'); await page.fill('#connection-name', 'Lokal testserver');
    await page.fill('#base-url', `http://127.0.0.1:${server.address().port}/v1`); empty=true; await page.click('#save-connection');
    await page.locator('#setup-ai').filter({hasText:'uden modeller'}).waitFor();
    const connection = (await page.evaluate(() => window.harness.connectionState())).value.connections[0];
    assert.equal(requests, 1);
    assert.equal(await page.isVisible('#setup-provider'),false);
    await page.locator('#setup-ai').filter({ hasText: 'uden modeller' }).waitFor();
    assert.equal(await page.isDisabled('#setup-continue'), true);
    empty = false; available = false; await page.click('#setup-test');
    await page.locator('#setup-ai').filter({ hasText: 'mislykkedes' }).waitFor();
    assert.equal(await page.isDisabled('#setup-continue'), true);
    available = true; await page.click('#setup-test');
    await page.locator('#setup-ai').filter({ hasText: 'Forbindelsen svarer.' }).waitFor();
    await page.click('#setup-continue');
    await app.evaluate(({ dialog }, project) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [project] }); }, project);
    await page.click('#open'); await page.waitForFunction(() => document.querySelector('#model-select').options.length === 2);
    assert.equal(await page.inputValue('#connection-select'), connection.id);
    await require('./ui-test-helpers.cjs').taskOptions(page); await page.locator('#model-catalog').evaluate(el => el.open = true); await page.selectOption('#model-select', 'test-model'); await page.click('#model-done');
    assert.equal(await page.locator('#model-options').evaluate(el => el.open), false);
    assert.match(await page.locator('#model-summary').textContent(), /Testmodel/); await page.fill('#prompt', 'Bevar min besked ved forbindelsesfejl.');
    available = false; await page.click('#send');
    await page.waitForSelector('#connection-warning:not([hidden])');
    assert.equal(await page.isVisible('#workspace'), true);
    assert.match(await page.locator('#connection-warning-text').textContent(), /gennemgås/);
    assert.equal(await page.isDisabled('#setup-continue'), true);
    await page.click('#dismiss-connection'); await page.waitForSelector('#workspace:not([hidden])');
    assert.equal(await page.inputValue('#prompt'), 'Bevar min besked ved forbindelsesfejl.');
    assert.deepEqual(await fs.readdir(project), []);
    await require('./ui-test-helpers.cjs').openSetup(page); available = true; await page.click('#setup-use-saved');await page.click('#setup-test');
    await page.locator('#setup-ai').filter({ hasText: 'Forbindelsen svarer.' }).waitFor();
    await page.screenshot({ path: path.join(root, 'genoprettet.png'), fullPage: true });
    await page.click('#setup-continue'); await app.close();
    const count = requests;
    const noGit = path.join(root, 'uden-git'); await fs.mkdir(noGit);
    page = await launch({ PATH: noGit });
    assert.match(await page.locator('#setup-git').textContent(), /Git blev ikke fundet/);
    assert.equal(await page.inputValue('#setup-connection'), connection.id);
    assert.equal(await page.isDisabled('#setup-continue'), true);
    assert.equal(requests, count);
    await page.click('#setup-local'); await page.waitForSelector('#create-form');
    await app.evaluate(({ dialog }, project) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [project] }); }, project);
    await page.click('#open'); await page.waitForSelector('#workspace:not([hidden])');
    assert.equal(await page.inputValue('#connection-select'), ''); assert.equal(requests, count);
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ status: 'bestået', root, checks: ['første start uden netværkskald', 'lokal adgang og bevaret projektkladde', 'opsætning og katalogkontrol', 'tomt katalog og utilgængelig server', 'genoprettet forbindelse', 'modelvalg i åbnet projekt', 'fejl før afsendelse bevarer besked og filer', 'genstart kræver ny kontrol', 'manglende Git blokerer ikke lokal adgang'] }));
  } finally { await app?.close(); server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); }
})().catch(error => { console.error(error); process.exitCode = 1; });
